# Generates the makefiles of vendor/samsung/lt03lte from proprietary-files.txt
# and the templates in vendor-makefiles/. Run by extract-files.sh.

set -e

DEVICE=lt03lte
VENDOR=samsung

MY_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ANDROID_ROOT="$(cd "$MY_DIR/../../.." && pwd)"
OUTDIR="vendor/$VENDOR/$DEVICE"
VENDOR_DIR="$ANDROID_ROOT/$OUTDIR"
BLOBS_MK="$VENDOR_DIR/$DEVICE-vendor-blobs.mk"

mkdir -p "$VENDOR_DIR/proprietary/ims"

# PRODUCT_COPY_FILES for every non-module entry
{
    echo "# This file is generated by device/$VENDOR/$DEVICE/setup-makefiles.sh"
    echo ""
    echo "PRODUCT_COPY_FILES += \\"
    grep -v -E '^(#|$|-)' "$MY_DIR/proprietary-files.txt" | sed 's/|.*//' | \
        while IFS=: read -r dest src; do
            echo "    $OUTDIR/proprietary/$src:$dest \\"
        done | sed '$ s/ \\$//'
} > "$BLOBS_MK"

# Prebuilt modules, product makefile and board config are fixed templates
# (Android.mk.template is not named Android.mk, or the build would parse it here)
cp "$MY_DIR/vendor-makefiles/Android.mk.template" "$VENDOR_DIR/Android.mk"
cp "$MY_DIR/vendor-makefiles/$DEVICE-vendor.mk" "$VENDOR_DIR/$DEVICE-vendor.mk"
cp "$MY_DIR/vendor-makefiles/BoardConfigVendor.mk" "$VENDOR_DIR/BoardConfigVendor.mk"
cp "$MY_DIR/vendor-makefiles/ims-Android.mk" "$VENDOR_DIR/proprietary/ims/Android.mk"

echo "Generated $OUTDIR makefiles ($(grep -c ':' "$BLOBS_MK") copied files)"
